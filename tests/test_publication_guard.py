from scripts.check_public_tree import inspect_file, inspect_commit
from pathlib import Path


def test_blocks_data_even_when_force_staged():
    assert inspect_file("tests/patient.edf", b"not actually an edf")
    assert inspect_file("reports/result.md", b"private result")
    assert inspect_file("tests/signal.npy", b"\x00")
    assert inspect_file("docs/result.svg", b"<svg/>")


def test_blocks_paths_and_attribution_but_allows_source():
    assert inspect_file("docs/example.md", ("/" + "Users" + "/person/private").encode())
    assert inspect_commit("fix: data contract\nCo-Authored-By: helper <helper@example.test>")
    assert inspect_commit("Codex <bot@example.test>\nfeat: migration")
    assert not inspect_file("tests/test_reader.py", b"def test_order(): pass\n")
    assert not inspect_commit("Maintainer <person@example.test>\nfeat: independent QC foundations")


def test_blocks_content_attribution_and_modern_token():
    assert inspect_file("docs/note.md", b"# Generated by " + b"helper")
    assert inspect_file("src/unsafe.py", ("github" + "_pat_" + "x" * 40).encode())


def test_scanner_does_not_flag_its_own_policy_patterns():
    path = Path(__file__).parents[1] / "scripts/check_public_tree.py"
    assert not inspect_file("scripts/check_public_tree.py", path.read_bytes())
